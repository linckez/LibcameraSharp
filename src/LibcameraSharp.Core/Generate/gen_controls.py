#!/usr/bin/env python3
"""Generate typed C# control, property and pixel-format definitions from libcamera's YAML.

Inputs (vendored per libcamera version under src/LibcameraSharp.Core/Generate/inputs/<version>/):
  control_ids_*.yaml, property_ids_*.yaml   every control/property, its type, size, docs, enum values
  control_ranges.yaml                       numeric id base per vendor (libcamera=0, draft=10000, rpi=20000, ...)
  formats.yaml + drm_fourcc.h               pixel format names -> DRM fourcc code + modifier
  log_categories.txt                        every LOG_DEFINE_CATEGORY name in libcamera's source (grep, see CONTRIBUTING)

Outputs (src/LibcameraSharp.Core/Generated/):
  ControlId.g.cs       `enum ControlId`, `enum PropertyId` — numeric ids exactly as libcamera assigns them
  ControlEnums.g.cs    one C# enum per enumerated control (AeState, AfMode, ...)
  Controls.g.cs        `static class Controls` / `Properties` with a typed key per entry, vendors nested
  PixelFormats.g.cs    `static class PixelFormats` with one PixelFormat per libcamera format, plus name lookups
  ControlKeys.g.cs     numeric id -> typed key lookups
  LogCategories.g.cs   `static class LogCategories` with libcamera's log category names

Id assignment mirrors libcamera's gen-controls.py: id = vendor_base + index_in_file + 1.
The YAML descriptions become the xmldoc, since they are written for exactly the reader at the call site.
"""
from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

import yaml

HEADER = "// <auto-generated> by src/LibcameraSharp.Core/Generate/gen_controls.py from libcamera's YAML — do not edit. </auto-generated>\n#nullable enable\n"
GENERATED_ATTR = '[System.CodeDom.Compiler.GeneratedCode("src/LibcameraSharp.Core/Generate/gen_controls.py", "{version}")]'
NAMESPACE = "LibcameraSharp"

# YAML element type -> (C# managed type, ControlType member name)
TYPE_MAP = {
    "bool": ("bool", "Bool"),
    "uint8_t": ("byte", "Byte"),
    "uint16_t": ("ushort", "Unsigned16"),
    "uint32_t": ("uint", "Unsigned32"),
    "int32_t": ("int", "Integer32"),
    "int64_t": ("long", "Integer64"),
    "float": ("float", "Float"),
    "string": ("string", "String"),
    "Rectangle": ("Rectangle", "Rectangle"),
    "Size": ("Size", "Size"),
    "Point": ("Point", "Point"),
}


@dataclass
class EnumValue:
    name: str
    value: int
    description: str


@dataclass
class Control:
    name: str
    vendor: str
    id: int
    element_type: str
    direction: str            # in | out | inout
    description: str
    size: list | None         # None = scalar, [] entries; a str entry means variable length
    enum_values: list[EnumValue] = field(default_factory=list)

    @property
    def is_array(self) -> bool:
        return self.size is not None

    @property
    def fixed_length(self) -> int | None:
        """Total element count for fixed-size arrays, None when variable or scalar."""
        if not self.is_array or any(isinstance(d, str) for d in self.size):
            return None
        n = 1
        for d in self.size:
            n *= int(d)
        return n

    @property
    def enum_name(self) -> str:
        return self.name

    @property
    def managed_type(self) -> str:
        """C# type used in Control<T>, e.g. `float[]`, `AeState`, `string`."""
        base = self.enum_name if self.enum_values else TYPE_MAP[self.element_type][0]
        return base + "[]" if self.is_array else base


# ---------------------------------------------------------------------------------------------
# Parsing
# ---------------------------------------------------------------------------------------------

def load_controls(files: list[Path], ranges: dict[str, int], mode: str) -> list[Control]:
    """Read every control from the given YAML files, assigning ids the way libcamera does."""
    out: list[Control] = []
    for path in files:
        data = yaml.safe_load(path.read_text())
        vendor = data["vendor"]
        if vendor not in ranges:
            raise SystemExit(f"{path.name}: vendor '{vendor}' has no id range in control_ranges.yaml")

        for index, entry in enumerate(data["controls"]):
            (name, spec), = entry.items()
            enum_values = [EnumValue(e["name"], int(e["value"]), (e.get("description") or "").strip())
                           for e in spec.get("enum", [])]
            out.append(Control(
                name=name,
                vendor=vendor,
                id=ranges[vendor] + index + 1,
                element_type=spec["type"],
                direction="out" if mode == "properties" else spec["direction"],
                description=(spec.get("description") or "").strip(),
                size=spec.get("size"),
                enum_values=enum_values,
            ))
    return out


class DrmFourcc:
    """The subset of drm_fourcc.h needed to turn DRM_FORMAT_* / *_MOD_* names into numbers."""

    _code = re.compile(r"#define (DRM_FORMAT_[A-Z0-9_]+)[ \t]+fourcc_code\('(.)', '(.)', '(.)', '(.)'\)")
    _vendor = re.compile(r"#define (DRM_FORMAT_MOD_VENDOR_[A-Z0-9_]+)[ \t]+(0x[0-9a-fA-F]+|[0-9]+)")
    _mod = re.compile(r"#define ([A-Za-z0-9_]+)[ \t]+fourcc_mod_code\(([A-Z0-9_]+), ([0-9a-fA-Fx]+)\)")

    def __init__(self, header: Path) -> None:
        self.codes: dict[str, int] = {}
        self.mods: dict[str, int] = {}
        vendors: dict[str, int] = {}
        for line in header.read_text().splitlines():
            if m := self._code.match(line):
                name, a, b, c, d = m.groups()
                self.codes[name] = ord(a) | ord(b) << 8 | ord(c) << 16 | ord(d) << 24
            elif m := self._vendor.match(line):
                vendors[m.group(1)] = int(m.group(2), 0)
            elif m := self._mod.match(line):
                name, vendor, value = m.groups()
                # fourcc_mod_code(vendor, val) = (vendor << 56) | (val & 0x00ffffffffffffff)
                self.mods[name] = (vendors[f"DRM_FORMAT_MOD_VENDOR_{vendor}"] << 56) | (int(value, 0) & 0x00FFFFFFFFFFFFFF)

    BIG_ENDIAN = 1 << 31


@dataclass
class PixelFormatDef:
    name: str
    fourcc: int
    modifier: int


def load_formats(path: Path, drm: DrmFourcc) -> list[PixelFormatDef]:
    out = []
    for entry in yaml.safe_load(path.read_text())["formats"]:
        (name, spec), = entry.items()
        fourcc = drm.codes[spec["fourcc"]]
        if spec.get("big_endian"):
            fourcc |= DrmFourcc.BIG_ENDIAN
        out.append(PixelFormatDef(name, fourcc, drm.mods[spec["mod"]] if "mod" in spec else 0))
    return out


